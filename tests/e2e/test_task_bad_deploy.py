"""A bad deploy from the injector to a bound task. The injector runs a 3-hour scenario on a simulated clock, through
the real k8s deploy driver against tests/fixtures/fake_kubectl_deploy.py: r1, a bad deploy of shipping (relation
deploy, intlShippingSlowdown 10sec, version_to 3.0.1), and d1, a benign_deploy of recommendation an hour earlier.
The telemetry is simulated from the realised schedule (tests/fixtures/make_corpus_l5.py `build`): while a release
is out its service's spans carry its service.version, and while r1's flag is on every quote takes 10 s. Then
`otb ref build` and `otb tasks instantiate`.

Ways it could fail, each asserted below:
- the schedule entry does not carry what the templates bind: kind fault, class bad_deploy, root service shipping,
  relation deploy, target, or a realised status;
- schedule_check finds no symptom for the bad deploy, or no new service.version for the benign one, so neither
  binds;
- l4-deploy-attribution binds no instance, or its truth names another service, the version the rollback restored,
  or a release time that is not the first span of the new version in the raw OTLP;
- the bad deploy's class is not bad_deploy, or a reader's latency_injection would not grade correct;
- another template binds the deploy fault with a class outside the vocabulary.

Evidence: tests/e2e/artifacts/task_bad_deploy.json.
"""

import json
import sys
from pathlib import Path

import pytest
from conftest import FIXTURES, ok, otb, write_artifact

from otb.archive import Archive
from otb.inject import K8sDecoys
from otb.scenario import RealisedSchedule
from otb.tasks.instantiate import load_entries
from otb.tasks.suite import read_jsonl

sys.path.insert(0, str(FIXTURES))
import make_corpus_l5

SCENARIO = """\
id: corpus-bad-deploy
seed: 5
duration_s: 10800
instances: [default]
min_gap_s: 0
note: synthetic; generated by tests/e2e/test_task_bad_deploy.py
slots:
  - { id: d1, kind: decoy, type: benign_deploy, target_in: [recommendation], params: { version_to: 3.0.1 }, start_s: { lo: 1800, hi: 1800 }, duration_s: { lo: 300, hi: 300 }, instance: default }
  - { id: r1, kind: fault, flag_in: [intlShippingSlowdown], variant_in: ["10sec"], relation: deploy, params: { version_to: 3.0.1 }, start_s: { lo: 5400, hi: 5400 }, duration_s: { lo: 900, hi: 900 }, instance: default }
"""  # noqa: E501
ORIGINAL = "service.namespace=opentelemetry-demo,service.version=2.0.0,service.criticality=high"


def first_span_of(corpus: Path, service: str, version: str) -> int:
    """From the archived OTLP/JSON, without the reference store: the earliest span start of service at version."""
    src = Archive.open(corpus, verify="full")
    first = None
    for ref, e in src.frames("traces", "g0"):
        for rs in json.loads(src.read(ref, e))["resourceSpans"]:
            attrs = {a["key"]: a["value"].get("stringValue") for a in rs["resource"]["attributes"]}
            if (attrs.get("service.name"), attrs.get("service.version")) != (service, version):
                continue
            for ss in rs["scopeSpans"]:
                for span in ss["spans"]:
                    t = int(span["startTimeUnixNano"])
                    first = t if first is None else min(first, t)
    assert first is not None, f"no span of {service} {version}"
    return first


def test_bad_deploy_binds_deploy_attribution(tmp_path: Path, artifacts: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    (bin_dir / "kubectl").write_text(
        f'#!/bin/sh\nexec "{sys.executable}" "{FIXTURES / "fake_kubectl_deploy.py"}" "$@"\n'
    )
    (bin_dir / "kubectl").chmod(0o755)
    env = [{"name": "OTEL_RESOURCE_ATTRIBUTES", "value": ORIGINAL}]
    labels = {"app.kubernetes.io/part-of": "opentelemetry-demo"}
    demo = {
        f"otb-demo-default/{d}": {
            "metadata": {"name": d, "namespace": "otb-demo-default", "labels": labels},
            "spec": {"template": {"spec": {"containers": [{"name": d, "env": env}]}}},
        }
        for d in ("shipping", "recommendation")
    }
    state = tmp_path / "cluster.json"
    state.write_text(json.dumps({"deployments": demo}))
    monkeypatch.setenv("PATH", f"{bin_dir}:{Path(sys.executable).parent}:/usr/bin:/bin")
    monkeypatch.setenv("FAKE_KUBECTL_STATE", str(state))

    corpus = tmp_path / "corpus-bad-deploy"
    make_corpus_l5.build(corpus, SCENARIO, K8sDecoys({"default": "otb-demo-default"}, {}))
    ok(otb("ref", "build", corpus, "--workers", "2"))
    ok(otb("tasks", "instantiate", "--corpus", corpus, "--seed", 7, "--out", tmp_path / "suite"))

    entries = {e.slot_id: e for e in RealisedSchedule.from_yaml((corpus / "schedule.yaml").read_bytes()).entries}
    r1 = entries["r1"]
    checks = {c["slot_id"]: c for c in json.loads((corpus / "derived/schedule_check.json").read_text())["checks"]}
    check = checks["r1"]
    truth = {t["instance_id"]: t for t in read_jsonl(tmp_path / "suite" / "truth.jsonl")}
    bound = {}
    for i in read_jsonl(tmp_path / "suite" / "instances.jsonl"):
        bound.setdefault(i["template_id"], []).append(
            {"control": i["control"], "answer": truth[i["instance_id"]]["answer"]}
        )
    suite = json.loads((tmp_path / "suite" / "suite.json").read_text())
    released = first_span_of(corpus, "shipping", "3.0.1")
    applied = next(a.at_ns for a in r1.actions if a.action == "deploy.apply" and a.detail["phase"] == "on")
    result = {
        "entry": {
            "status": r1.status, "kind": r1.kind, "flag": r1.flag, "fault_class": r1.fault_class,
            "root_service": r1.root_service, "relation": r1.relation, "target": r1.target,
        },
        "schedule_check": {k: check[k] for k in ("status", "measure", "signature")},
        "classes": next(e["classes"] for e in load_entries(corpus) if e["slot_id"] == "r1"),
        "d1": [entries["d1"].status, checks["d1"]["status"], checks["d1"]["effect"]],
        "deploy_attribution": bound.get("l4-deploy-attribution"),
        "bound_templates": sorted(bound),
        "dropped": sorted({(d["template_id"], d["reason"]) for d in suite["dropped"]}),
        "released_within_a_minute_of_the_change": 0 <= released - applied < 60 * 10**9,
        "resource_env_after": state.read_text().count(ORIGINAL),
    }  # fmt: skip
    write_artifact(artifacts / "task_bad_deploy.json", result | {"released_at": released})

    assert result["entry"] == {
        "status": "realised",
        "kind": "fault",
        "flag": "intlShippingSlowdown",
        "fault_class": "bad_deploy",
        "root_service": "shipping",
        "relation": "deploy",
        "target": "shipping",
    }
    assert result["schedule_check"] == {
        "status": "realised",
        "measure": "slow_spans",
        "signature": "oteldemo.ShippingService/GetQuote",
    }
    assert result["deploy_attribution"] == [
        {
            "control": "none",
            "answer": {"deploy_caused": True, "service": "shipping", "version": "3.0.1", "released_at": released},
        },
        {
            "control": "decoy",
            "answer": {"deploy_caused": False, "service": None, "version": None, "released_at": None},
        },
    ]
    assert result["classes"] == ["bad_deploy", "latency_injection"]
    assert result["d1"] == ["realised", "realised", {"new_versions": ["3.0.1"]}]
    assert result["released_within_a_minute_of_the_change"]
    assert result["resource_env_after"] == 2, "both Deployments are back on their original attributes"
    assert not [d for d in result["dropped"] if "not in the vocabulary" in d[1]]
