"""Writes the Kubernetes files that restate a repo file or a profile budget, and refuses drift.

    uv run python deploy/k8s/stacks/generate.py           rewrite every output
    uv run python deploy/k8s/stacks/generate.py --check   exit 1, naming each output that differs

The k8s runtime installs a chart from exactly one values file and applies plain manifests as they are (no
--set-file, no templating beyond `{profile}` in a path). So each config compose mounts becomes a ConfigMap here,
byte for byte; Tempo's config, which its chart only takes as a value, is appended to its values; every
collector's values are the shared base plus the stack's name, labels, credentials and ConfigMap; and ClickHouse,
a manifests release, gets one manifest per profile from that profile's `clickhouse` entry.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[3]
HERE = REPO / "deploy" / "k8s" / "stacks"
PROFILES = ("kind", "gke", "gke-pilot")
HEADER = "# Generated by deploy/k8s/stacks/generate.py from {src}. Edit those, then rerun it.\n"
CLICKHOUSE_IMAGE = (
    "clickhouse/clickhouse-server:26.8.15.10@sha256:9716a352d25f538bd19d868b001141e7a60e4d035bc9b823658c6a071660aa61"
)

# stack -> ConfigMap -> key -> repo file
CONFIGMAPS = {
    "b1-lgtm": {
        "ingest-b1-config": {"relay": "stacks/b1-lgtm/collector.yaml"},
        "prometheus-config": {"prometheus.yml": "stacks/b1-lgtm/config/prometheus.yml"},
        "loki-config": {"config.yaml": "stacks/b1-lgtm/config/loki.yaml"},
        "grafana-datasources": {"otb.yaml": "stacks/b1-lgtm/config/grafana/datasources.yaml"},
        "grafana-token-script": {"grafana_token.py": "deploy/k8s/stacks/b1-lgtm/grafana_token.py"},
    },
    "b3-clickhouse": {
        "ingest-b3-config": {"relay": "stacks/b3-clickhouse/collector.yaml"},
        "clickhouse-config": {
            "memory.xml": "stacks/b3-clickhouse/config/memory.xml",
            "profiles.xml": "stacks/b3-clickhouse/config/profiles.xml",
        },
    },
    "b4-parseable": {
        "ingest-b4-config": {"relay": "stacks/b4-parseable/collector.yaml"},
        "parseable-env-script": {"parseable_env.py": "deploy/k8s/stacks/b4-parseable/parseable_env.py"},
    },
}

# stack -> (collector name, credentials its collector.yaml reads from the environment)
COLLECTORS = {
    "b1-lgtm": ("ingest-b1", []),
    "b3-clickhouse": ("ingest-b3", ["B3_CH_ADMIN_PASSWORD"]),
    "b4-parseable": ("ingest-b4", ["B4_PARSEABLE_USERNAME", "B4_PARSEABLE_PASSWORD"]),
}


class _Dumper(yaml.SafeDumper):
    pass


def _str(dumper: yaml.SafeDumper, s: str) -> yaml.ScalarNode:
    return dumper.represent_scalar("tag:yaml.org,2002:str", s, style="|" if "\n" in s else None)


_Dumper.add_representer(str, _str)


def dump(docs: list[object]) -> str:
    return yaml.dump_all(docs, Dumper=_Dumper, sort_keys=False, width=120)


def configmaps(stack: str) -> str:
    docs = []
    for name, keys in CONFIGMAPS[stack].items():
        data = {key: (REPO / src).read_text() for key, src in keys.items()}
        docs.append(
            {
                "apiVersion": "v1",
                "kind": "ConfigMap",
                "metadata": {"name": name, "labels": {"otb.stack": stack}},
                "data": data,
            }
        )
    srcs = sorted({src for keys in CONFIGMAPS[stack].values() for src in keys.values()})
    return HEADER.format(src=", ".join(srcs)) + dump(docs)


def collector(stack: str) -> str:
    name, creds = COLLECTORS[stack]
    base = HERE / "collector.base.yaml"
    extra: dict[str, object] = {
        "fullnameOverride": name,
        "configMap": {"create": False, "existingName": f"{name}-config"},
        "podLabels": {"otb.stack": stack, "otb.role": "ingest"},
    }
    if creds:
        extra["extraEnvs"] = [
            {"name": c, "valueFrom": {"secretKeyRef": {"name": "otb-credentials", "key": c}}} for c in creds
        ]
    return HEADER.format(src="deploy/k8s/stacks/collector.base.yaml") + _append(base, extra)


def tempo() -> str:
    base = HERE / "b1-lgtm" / "tempo.base.yaml"
    src = "stacks/b1-lgtm/config/tempo.yaml"
    return HEADER.format(src=f"deploy/k8s/stacks/b1-lgtm/tempo.base.yaml, {src}") + _append(
        base, {"config": (REPO / src).read_text()}
    )


def _append(base: Path, extra: dict[str, object]) -> str:
    """The base file's text, comments kept, then `extra` as further top-level keys."""
    clash = set(yaml.safe_load(base.read_text()) or {}) & set(extra)
    if clash:
        sys.exit(f"{base}: sets {sorted(clash)}, which generate.py writes")
    return base.read_text().rstrip("\n") + "\n" + dump([extra]).removeprefix("---\n")


def clickhouse(profile: str) -> str:
    p = yaml.safe_load((REPO / "deploy/k8s/profiles" / f"{profile}.yaml").read_text())["clickhouse"]
    labels = {"otb.stack": "b3-clickhouse"}
    claim: dict[str, object] = {
        "accessModes": ["ReadWriteOnce"],
        "resources": {"requests": {"storage": p["persistence"]["size"]}},
    }
    if p["persistence"].get("storageClass"):
        claim["storageClassName"] = p["persistence"]["storageClass"]
    service = {
        "apiVersion": "v1",
        "kind": "Service",
        "metadata": {"name": "clickhouse", "labels": labels},
        "spec": {
            "clusterIP": "None",
            "selector": {"app.kubernetes.io/name": "clickhouse"},
            "ports": [
                {"name": "http", "port": 8123, "targetPort": 8123},
                {"name": "native", "port": 9000, "targetPort": 9000},
            ],
        },
    }
    env = [
        {"name": "CLICKHOUSE_USER", "value": "default"},
        {
            "name": "CLICKHOUSE_PASSWORD",
            "valueFrom": {"secretKeyRef": {"name": "otb-credentials", "key": "B3_CH_ADMIN_PASSWORD"}},
        },
        {"name": "CLICKHOUSE_DB", "value": "otel"},
        {"name": "CLICKHOUSE_DEFAULT_ACCESS_MANAGEMENT", "value": "1"},
        {"name": "B3_MAX_QUERY_MEMORY", "value": str(p["maxQueryMemory"])},
        {"name": "B3_SPILL_BYTES", "value": str(p["spillBytes"])},
    ]
    mounts = [
        {"name": "data", "mountPath": "/var/lib/clickhouse"},
        {
            "name": "config",
            "mountPath": "/etc/clickhouse-server/config.d/otb-memory.xml",
            "subPath": "memory.xml",
            "readOnly": True,
        },
        {
            "name": "config",
            "mountPath": "/etc/clickhouse-server/users.d/otb-profiles.xml",
            "subPath": "profiles.xml",
            "readOnly": True,
        },
    ]
    statefulset = {
        "apiVersion": "apps/v1",
        "kind": "StatefulSet",
        "metadata": {"name": "clickhouse", "labels": labels},
        "spec": {
            "serviceName": "clickhouse",
            "replicas": 1,
            "selector": {"matchLabels": {"app.kubernetes.io/name": "clickhouse"}},
            "template": {
                "metadata": {"labels": {"app.kubernetes.io/name": "clickhouse", **labels, "otb.role": "backend"}},
                "spec": {
                    "containers": [
                        {
                            "name": "clickhouse",
                            "image": CLICKHOUSE_IMAGE,
                            "env": env,
                            "ports": [
                                {"name": "http", "containerPort": 8123},
                                {"name": "native", "containerPort": 9000},
                            ],
                            "readinessProbe": {
                                "httpGet": {"path": "/ping", "port": 8123},
                                "periodSeconds": 10,
                                "failureThreshold": 30,
                            },
                            "resources": p["resources"],
                            "volumeMounts": mounts,
                        }
                    ],
                    "volumes": [{"name": "config", "configMap": {"name": "clickhouse-config"}}],
                },
            },
            "volumeClaimTemplates": [{"metadata": {"name": "data", "labels": labels}, "spec": claim}],
        },
    }
    src = f"deploy/k8s/stacks/generate.py (the manifest) and deploy/k8s/profiles/{profile}.yaml (clickhouse)"
    note = (
        "# B3 ClickHouse as compose runs it: the official image by compose's digest, the stack's config.d and users.d\n"
        "# files from the clickhouse-config ConfigMap, and a headless Service named clickhouse.\n"
    )
    return HEADER.format(src=src) + note + dump([service, statefulset])


def outputs() -> dict[Path, str]:
    out = {HERE / s / "configmaps.yaml": configmaps(s) for s in CONFIGMAPS}
    out |= {HERE / s / "collector.yaml": collector(s) for s in COLLECTORS}
    out[HERE / "b1-lgtm" / "tempo.yaml"] = tempo()
    out |= {HERE / "b3-clickhouse" / f"clickhouse-{p}.yaml": clickhouse(p) for p in PROFILES}
    return out


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    stale = []
    for path, text in outputs().items():
        if path.exists() and path.read_text() == text:
            continue
        if a.check:
            stale.append(str(path.relative_to(REPO)))
        else:
            path.write_text(text)
            print(f"wrote {path.relative_to(REPO)}")
    for s in stale:
        print(f"stale: {s} (run deploy/k8s/stacks/generate.py)")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
